import { textContent, clip } from './text.js';

/** Plugin-written notes; the window message injects neither (the summary is already there). */
export const HANDOFF_NOTE = 'handoff.md';
export const HANDOFF_LOG = 'handoff-log.md';
export const HANDOFF_PATHS = new Set([HANDOFF_NOTE, HANDOFF_LOG].map(path => `self/notes/${path}`));

const MAX_BODY_CHARS = 200_000;

/** After a committed rotation: overwrite handoff.md with a bounded summary copy
 * and append one line to handoff-log.md. Idempotent per window, so a retried call
 * never duplicates a log line.
 * @returns whether anything was written.
 */
export async function recordHandoff(states, session, signal, windowId) {
  const state = states.get(session);
  const index = windowId === undefined ? state.windows.length - 1 : state.windows.findIndex(w => w.window_id === windowId);
  const incoming = state.windows[index];
  const outgoing = state.windows[index - 1];
  if (!outgoing?.summary_item_id) return false;
  const log = state.notes.files.get(`self/notes/${HANDOFF_LOG}`)?.content ?? '';
  if (log.split('\n').some(line => line.startsWith(`- ${incoming.window_id} `))) return false;

  const summarySeq = Number(outgoing.summary_item_id.slice('item_'.length));
  const data = session.eventAt(summarySeq).data;
  // The summarizer's raw output is the full body. Legacy (<= 0.3.x) summaries
  // embedded a clipped copy in their window header.
  const header = textContent(data.summary);
  const legacy = header.startsWith('<context_window ');
  const generated = outgoing.summary_kind === 'generated'
    && (textContent(data.rawOutput).trim()
      || (legacy ? /<generated_handoff>\n([\s\S]*)\n<\/generated_handoff>/.exec(header)?.[1] : header.trim()));
  const body = clip(generated || header, MAX_BODY_CHARS);
  const source = generated ? `generated by ${data.provider}/${data.model}` : `${outgoing.summary_kind} record`;
  const time = new Date().toISOString();

  await states.writeNote(session, HANDOFF_NOTE, [
    `# Latest handoff: ${outgoing.window_id} → ${incoming.window_id}`,
    `Written automatically at ${time} when the window rotated (${source}, summary ${outgoing.summary_item_id}). Replaced on every rotation; ${HANDOFF_LOG} lists earlier ones, and history_read returns their full text.`,
    '',
    body,
    '',
  ].join('\n'), 'write', signal);
  await states.writeNote(session, HANDOFF_LOG,
    `- ${incoming.window_id} ${time} ${outgoing.summary_item_id} ${source}: ${clip(body.split('\n').find(line => line.trim() && !line.startsWith('#'))?.trim() ?? '', 160)}\n`,
    'append', signal);
  return true;
}
